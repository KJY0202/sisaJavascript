const a = new Date();
console.log(a.getDate()); // 일 (1~31)
console.log(a.getDay()); // 요일 (0: 일요일, 1: 월요일, ...)
console.log(a.getHours()); // 시 (0~23)
console.log(a.getMinutes()); // 분 (0~59)
console.log(a.getSeconds()); // 초 (0~59)
console.log(a.getTime()); // 1970년도에서 몇초 흐름 == 밀리초 타임스탬프 (날짜 차이 계산용)
